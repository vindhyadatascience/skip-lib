        val actual = anyHashableCastValue(value, targetSwiftType = target)
        assertEquals("$label is $target", nativeIs, actual != null)
        if (expected == null) { assertNull("$label as? $target", actual); return }
        assertNotNull("$label as? $target", actual)
        assertEquals("$label target representation $target", expected::class, actual!!::class)
        when (expected) {
            is Double -> assertEquals("$label Double bits", java.lang.Double.doubleToRawLongBits(expected), java.lang.Double.doubleToRawLongBits(actual as Double))
            is Float -> assertEquals("$label Float bits", java.lang.Float.floatToRawIntBits(expected), java.lang.Float.floatToRawIntBits(actual as Float))
            else -> assertEquals("$label as? $target", expected, actual)
        }
    }

